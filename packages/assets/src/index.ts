/**
 * Sanitise imported GeoJSON / JSON content (REQUIREMENT 122).
 *
 * Rejects prototype-pollution keys, `javascript:` URLs and function-valued
 * fields, and hard-caps coordinate array sizes so a hostile file cannot exhaust
 * memory during parsing.
 */
export function sanitizeImportedJson(raw: unknown, opts: { maxNodes?: number } = {}): { ok: boolean; data?: unknown; errors: string[] } {
  const errors: string[] = [];
  const maxNodes = opts.maxNodes ?? 500000;
  let nodes = 0;

  const walk = (value: unknown, depth: number): unknown => {
    if (depth > 64) {
      errors.push('Nested too deeply (>64 levels)');
      return null;
    }
    if (nodes++ > maxNodes) {
      errors.push(`Document exceeds ${maxNodes.toLocaleString()} nodes`);
      return null;
    }
    if (value === null || typeof value !== 'object') {
      if (typeof value === 'string' && /^\s*javascript:/i.test(value)) {
        errors.push('Rejected a javascript: URL');
        return '';
      }
      return value;
    }
    if (Array.isArray(value)) return value.map((v) => walk(v, depth + 1));
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (k === '__proto__' || k === 'constructor' || k === 'prototype') {
        errors.push(`Rejected disallowed key "${k}"`);
        continue;
      }
      out[k] = walk(v, depth + 1);
    }
    return out;
  };

  const data = walk(raw, 0);
  return { ok: errors.length === 0, data, errors };
}

/** Only http(s) and blob/data URLs are ever loaded. */
export function isSafeUrl(url: string): { ok: boolean; reason?: string } {
  if (!url) return { ok: false, reason: 'Empty URL' };
  if (url.startsWith('blob:') || url.startsWith('data:image/') || url.startsWith('data:model/')) return { ok: true };
  try {
    const u = new URL(url, typeof location !== 'undefined' ? location.href : 'http://localhost');
    if (u.protocol === 'http:' || u.protocol === 'https:') return { ok: true };
    return { ok: false, reason: `Protocol "${u.protocol}" is not allowed` };
  } catch {
    return { ok: false, reason: 'Not a valid URL' };
  }
}

/**
 * packages/world — map/terrain provider abstraction (REQUIREMENT 012, 019).
 *
 * The scene core never knows which provider it is talking to. Every external
 * basemap / DEM / geocoder source sits behind one of these interfaces, so the
 * app works with zero providers configured (REQUIREMENT 119) and can add
 * OpenStreetMap, MapLibre DEM, Terrarium or a user's own tile server without
 * touching the renderer.
 *
 * Every method takes an AbortSignal. Stale requests must be discardable
 * (REQUIREMENT: every async job is cancellable).
 */

export interface TileDescriptor {
  z: number;
  x: number;
  y: number;
}

export interface ProviderInfo {
  id: string;
  name: string;
  kind: 'raster-imagery' | 'vector' | 'terrain-dem' | 'geocoder';
  attribution: string;
  license: string;
  minZoom: number;
  maxZoom: number;
  /** True when the provider needs no network access at all. */
  offline: boolean;
  /** True when a key/URL must be supplied by the user before use. */
  requiresConfiguration: boolean;
}

export interface RasterTileResult {
  data: Float32Array | Uint8ClampedArray;
  width: number;
  height: number;
  /** Elevation encoding, when the tile is a DEM. */
  encoding?: 'mapbox' | 'terrarium' | 'gray16' | 'rgba';
  bytes: number;
}

export interface ImageryProvider {
  info: ProviderInfo;
  fetchTile(t: TileDescriptor, signal: AbortSignal): Promise<{ blob: Blob; bytes: number }>;
}

export interface TerrainProvider {
  info: ProviderInfo;
  fetchDem(t: TileDescriptor, signal: AbortSignal): Promise<RasterTileResult>;
}

export interface GeocodeResult {
  name: string;
  lat: number;
  lon: number;
  /** Suggested camera distance in metres for the result's extent. */
  suggestedDistance: number;
  source: string;
}

export interface GeocoderProvider {
  info: ProviderInfo;
  search(query: string, signal: AbortSignal): Promise<GeocodeResult[]>;
}

/* ------------------------------------------------------------- registry --- */

export class ProviderRegistry {
  private providers = new Map<string, ProviderInfo & { instance: unknown }>();

  register(p: ProviderInfo, instance: unknown): void {
    this.providers.set(p.id, { ...p, instance });
  }

  get<T>(id: string): T | null {
    const p = this.providers.get(id);
    return p ? (p.instance as T) : null;
  }

  info(id: string): ProviderInfo | null {
    const p = this.providers.get(id);
    if (!p) return null;
    const { instance: _instance, ...info } = p;
    void _instance;
    return info as ProviderInfo;
  }

  list(kind?: ProviderInfo['kind']): ProviderInfo[] {
    return [...this.providers.values()]
      .filter((p) => !kind || p.kind === kind)
      .map(({ instance: _i, ...rest }) => {
        void _i;
        return rest as ProviderInfo;
      });
  }

  unregister(id: string): void {
    this.providers.delete(id);
  }
}

